    /// <summary>Делает окно «невидимым для фокуса»: не активируется по клику и не попадает в Alt+Tab.</summary>
    public static void MakeNoActivate(IntPtr hwnd, bool clickThrough = false)
    {
        long ex = GetWindowLongPtr(hwnd, GWL_EXSTYLE).ToInt64();
        ex |= WS_EX_NOACTIVATE | WS_EX_TOOLWINDOW | WS_EX_TOPMOST;
        if (clickThrough) ex |= WS_EX_TRANSPARENT;
        SetWindowLongPtr(hwnd, GWL_EXSTYLE, new IntPtr(ex));
    }
