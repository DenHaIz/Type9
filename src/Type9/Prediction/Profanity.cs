using System.Text.RegularExpressions;

namespace Type9.Prediction;

/// <summary>
/// Нецензурные слова из корпуса (субтитры ими полны) не предлагаются сами по себе — только если пользователь
/// уже писал их сам (есть в личном словаре). Ключи нормализованы: нижний регистр, ё→е.
/// </summary>
public static partial class Profanity
{
    // Корни мата с типовыми приставками; исключения — «страхуй», «мандарин», «хулиган», «небо», «хлеб»
    [GeneratedRegex(
        @"^(?:вы|за|у|от|на|при|до|раз|рас|по|под|об|въ|съ|подъ|объ|изъ|разъ|долбо|не|недо|пере)?еб(?:а|у|л|н|и|е|ы|ок|уч|ищ)" +
        @"|^(?:вы|за|по|на|от|до|при|раз|рас|пере)?ху(?:й|е|я|и|ё)(?!ж)" +
        @"|пизд|^бля(?!ш|х)|^муд(?:ак|ил|о(?!в))|^пид(?:ор|ар|р)|^педик|^педераст|залуп|^гандон|дроч|^шлюх|^сук(?:а|и|е|у|ой|ин|ины)$|^манд(?:а|ой|у|ы)$")]
    private static partial Regex Obscene();

    public static bool IsObscene(string key) => key.Length >= 3 && Obscene().IsMatch(key) && !key.Contains("страху");
}
